def _patch_conn_info_npl(pkt, client_ip, target_ip):
    """Patch the client/server IPs in the P3_NPL connection-info ASCII TLV.

    The template string carries hardcoded IPs from the pcap capture session:
      fields  5 / 17  = client IP = 192.168.88.2
      fields  7 / 18  = server IP = 192.168.88.3

    Older kernels (e.g. NW 742) validate these against the actual TCP endpoints
    and reset the RFC connection with WSAECONNRESET if they do not match.

    The TLV format is: [01 27] [2-byte BE length] [ASCII string incl. NUL].
    Replacements are confined to that region; the 2-byte length prefix and the
    CPIC size fields at offsets 48 and -8 are updated to reflect any size change.
    """
    old_client = _NPL_CONN_INFO_CLIENT_IP
    old_server = _NPL_CONN_INFO_SERVER_IP
    new_client = client_ip.encode('ascii') if client_ip else old_client
    new_server = target_ip.encode('ascii') if target_ip else old_server

    if new_client == old_client and new_server == old_server:
        return pkt

    marker_off = bytes(pkt).find(b'\x01\x27')
    if marker_off < 0:
        return pkt

    len_off = marker_off + 2
    old_str_len = struct.unpack('>H', bytes(pkt[len_off:len_off + 2]))[0]
    str_start = marker_off + 4
    str_end = str_start + old_str_len

    old_str = bytes(pkt[str_start:str_end])
    new_str = old_str.replace(old_client, new_client).replace(old_server, new_server)

    if new_str == old_str:
        return pkt

    # Update the 2-byte length prefix to reflect the new string size
    struct.pack_into('>H', pkt, len_off, len(new_str))

    # Splice new string in; bytearray handles variable-length slice assignment
    pkt[str_start:str_end] = new_str

    # Adjust CPIC size fields (conn-info is inside the CPIC block)
    cpic_delta = len(new_str) - old_str_len
    if cpic_delta != 0:
        old_cpic = struct.unpack('>I', bytes(pkt[48:52]))[0]
        struct.pack_into('>I', pkt, 48, old_cpic + cpic_delta)
        old_trailer = struct.unpack('>I', bytes(pkt[len(pkt) - 8:len(pkt) - 4]))[0]
        struct.pack_into('>I', pkt, len(pkt) - 8, old_trailer + cpic_delta)

    return pkt


# 8-byte suffix shared by ALL session PTEs: 0xe1000000 + 4-byte client IP
# Variant PTEs (cc8b/cc90 subtypes) not covered by the exact 16-byte MAIN/TH
# replacements still need their client-IP tail updated, or the server rejects
# the packet with "Conversation not found".
_PTE_IP_SUFFIX_OLD = bytes.fromhex('e1000000') + _NOARGS_MAIN_PTE[12:16]  # e10000000a141e41

# TH (SAP Transport Header) routing: 32-byte space-padded field identifying the
# application server that should handle the RFC call.  Format: {SID}/{host}_{SID}_00
# This appears TWICE in each P3 template (routing + authentication block).
# The P2 TP name follows the shorter pattern {SID}-SXPG (always 8 bytes).
_OLD_TH_ROUTING  = b'A4H/vhcala4hci_A4H_00' + b' ' * 11   # 32 bytes, space-padded
_OLD_P2_TP_NAME  = b'A4H-SXPG'                             #  8 bytes
_OLD_NPL_TP_NAME = b'npl-sxpg'                             #  8 bytes (ASCII in P2_NPL)

def _patch_conn_info_rfcsi(pkt, client_ip, target_ip):
    """Patch client/server IPs in the P3_RFCSI connection-info TLV (01 05 marker).

    The template carries IPs from the capture session: client=10.20.30.15,
    server=10.20.30.3.  Replaces both with the actual session IPs and updates
    the 2-byte TLV length plus the CPIC size fields at offsets 48 and 56.

    The byte sequence 01 05 also appears inside the CPIC capability flags earlier
    in the packet; we skip any match whose 2-byte length field falls outside a
    plausible range for a connection-info string (50–600 bytes).
    """
    old_client = _RFCSI_CONN_CLIENT_IP
    old_server = _RFCSI_CONN_SERVER_IP
    new_client = client_ip.encode('ascii') if client_ip else old_client
    new_server = target_ip.encode('ascii') if target_ip else old_server

    if new_client == old_client and new_server == old_server:
        return pkt

    data = bytes(pkt)
    search_from = 0
    marker_off = -1
    old_str_len = 0
    while True:
        idx = data.find(b'\x01\x05', search_from)
        if idx < 0 or idx + 4 > len(data):
            return pkt
        length = struct.unpack('>H', data[idx + 2:idx + 4])[0]
        if 50 <= length <= 600:
            marker_off = idx
            old_str_len = length
            break
        search_from = idx + 1

    len_off = marker_off + 2
    str_start = marker_off + 4
    str_end = str_start + old_str_len

    old_str = bytes(pkt[str_start:str_end])
    new_str = old_str.replace(old_client, new_client).replace(old_server, new_server)
    if new_str == old_str:
        return pkt

    struct.pack_into('>H', pkt, len_off, len(new_str))
    pkt[str_start:str_end] = new_str

    cpic_delta = len(new_str) - old_str_len
    if cpic_delta != 0:
        for off in (48, 56):
            old_v = struct.unpack('>I', bytes(pkt[off:off + 4]))[0]
            struct.pack_into('>I', pkt, off, old_v + cpic_delta)

    return pkt


def _patch_rfcsi_routing(pkt, sid, appserver):
    """Patch routing fields in a P3_RFCSI bytearray.

    Replaces TH routing (length-neutral 32 bytes), the connection-info SID tag,
    and the CPIC UTF-16 LE parameter block (instance name, SID, hostname).
    CPIC size adjustments use offsets 48 and 56 (not end-8 as in SAPXPG templates).
    """
    # TH routing (ASCII, length-neutral)
    new_th = _make_th_routing_padded(sid, appserver)
    pkt = bytearray(bytes(pkt).replace(_OLD_TH_ROUTING, new_th))

    # Connection-info SID tag (ASCII, length-neutral)
    sid_b = sid[:3].encode('ascii')
    pkt = bytearray(bytes(pkt).replace(b'-16-A4H-', b'-16-' + sid_b + b'-'))

    # CPIC UTF-16 LE parameter block
    cpic_delta = 0
    pkt, d = _replace_utf16_field(pkt, 'vhcala4hci_A4H_00', f'{appserver}_{sid}_00')
    cpic_delta += d
    pkt, d = _replace_utf16_field(pkt, 'A4H', sid[:3])
    cpic_delta += d
    pkt, d = _replace_utf16_field(pkt, 'vhcala4hci', appserver)
    cpic_delta += d

    if cpic_delta != 0:
        for off in (48, 56):
            old_v = struct.unpack('>I', bytes(pkt[off:off + 4]))[0]
            struct.pack_into('>I', pkt, off, old_v + cpic_delta)

    return pkt


